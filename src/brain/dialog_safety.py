"""Защита памяти диалога от очистки из обычной речи (SAFE-01, D-01..D-03).

Очистка памяти диалога выполняется только через HITL-карточку слэш-команды
/clear или /reset. Текст, голос, LLM-маршрут и движок диалога очистку не
выполняют: бот отвечает предупреждением и просит ввести команду вручную.
Модуль чистый (без импортов), чтобы его мог импортировать и src.brain, и бот
без нарушения контрактов import-linter.
"""

# Единый список триггеров очистки (раньше жил двумя расходящимися кортежами
# в intent_router и secretary_dialog).
CLEAR_DIALOG_TRIGGERS: tuple[str, ...] = (
    "/clear",
    "/reset",
    "очисти диалог",
    "забудь контекст",
    "сброс",
)

CLEAR_DIALOG_TEXT_WARNING = (
    "⚠️ **Очистка памяти диалога из обычного сообщения или голоса не выполняется.**\n\n"
    "Она стирает память диалога с секретарём. Чтобы подтвердить очистку, "
    "введите вручную следующим сообщением команду /clear: она покажет карточку "
    "подтверждения. После очистки память можно восстановить кнопкой «Восстановить»."
)

_TRAILING_PUNCTUATION = " \t\r\n.!?…"


def is_clear_dialog_request(text: str | None) -> bool:
    """Истина, если текст (без регистра и хвостовой пунктуации) просит очистить диалог."""
    if not text:
        return False
    normalized = text.strip().casefold().rstrip(_TRAILING_PUNCTUATION)
    return normalized in CLEAR_DIALOG_TRIGGERS
